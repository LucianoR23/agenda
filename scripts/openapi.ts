/**
 * Generates openapi.yaml (everything) and openapi.sunday.yaml (Sunday's tools) from the Zod contract.
 *   pnpm openapi:gen      write the files
 *   pnpm openapi:check    fail if examples are invalid or a committed file is stale (CI)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { stringify } from "yaml";
import { generateOpenApiDocument, routes, validateExamples, withoutExamples } from "../src/contract/openapi";
import { SUNDAY_OPERATIONS } from "../src/contract/sunday";

const check = process.argv.includes("--check");

const failures = validateExamples();
for (const id of SUNDAY_OPERATIONS) {
  const r = routes.find((x) => x.operationId === id);
  if (!r) failures.push(`sunday: ${id} is not a route`);
  else if (!r.token) failures.push(`sunday: ${id} doesn't accept API tokens (no \`token\` scope)`);
}
if (failures.length) {
  console.error(`✗ ${failures.length} problem(s):\n  ${failures.join("\n  ")}`);
  process.exit(1);
}

const header = "# GENERATED by `pnpm openapi:gen` from src/contract — do not edit by hand.\n";
const toYaml = (doc: unknown) => header + stringify(doc, { lineWidth: 0, aliasDuplicateObjects: false });

const files: Array<[string, string]> = [
  ["openapi.yaml", toYaml(generateOpenApiDocument())],
  // what /api/openapi.sunday.json serves (minus the server URL, which follows APP_ORIGIN)
  ["openapi.sunday.yaml", toYaml(withoutExamples(generateOpenApiDocument("sunday")))],
];

let stale = false;
for (const [file, yaml] of files) {
  if (check) {
    let current = "";
    try {
      current = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
    } catch {}
    if (current !== yaml) {
      console.error(`✗ Contract drift: ${file} out of date. Run \`pnpm openapi:gen\` and commit.`);
      stale = true;
    }
  } else writeFileSync(file, yaml);
}
if (stale) process.exit(1);
console.log(
  check
    ? `✓ ${routes.length} routes (${SUNDAY_OPERATIONS.length} for Sunday), examples valid, specs up to date`
    : `✓ wrote openapi.yaml (${routes.length} routes) and openapi.sunday.yaml (${SUNDAY_OPERATIONS.length} operations)`,
);
