/**
 * Generates openapi.yaml from the Zod contract.
 *   pnpm openapi:gen      write the file
 *   pnpm openapi:check    fail if examples are invalid or the committed file is stale (CI)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { stringify } from "yaml";
import { generateOpenApiDocument, routes, validateExamples } from "../src/contract/openapi";

const check = process.argv.includes("--check");

const failures = validateExamples();
if (failures.length) {
  console.error(`✗ ${failures.length} invalid example(s):\n  ${failures.join("\n  ")}`);
  process.exit(1);
}

const yaml =
  "# GENERATED by `pnpm openapi:gen` from src/contract — do not edit by hand.\n" +
  stringify(generateOpenApiDocument(), { lineWidth: 0, aliasDuplicateObjects: false });

const file = "openapi.yaml";

if (check) {
  let current = "";
  try {
    current = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  } catch {}
  if (current !== yaml) {
    console.error(`✗ Contract drift: ${file} out of date. Run \`pnpm openapi\` and commit.`);
    process.exit(1);
  }
  console.log(`✓ ${routes.length} routes, examples valid, ${file} up to date`);
} else {
  writeFileSync(file, yaml);
  console.log(`✓ wrote ${file} (${routes.length} routes)`);
}
