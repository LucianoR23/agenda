/**
 * Generates openapi.yaml and docs/api-examples.md from the Zod contract.
 *   pnpm openapi          write both files
 *   pnpm openapi:check    fail if examples are invalid or the committed files are stale (CI)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { stringify } from "yaml";
import {
  effectiveResponses,
  generateOpenApiDocument,
  reason,
  routes,
  validateExamples,
  webhookExamples,
} from "../src/contract/openapi";
import type { Exchange, RouteDef } from "../src/contract/route-def";

const check = process.argv.includes("--check");

const failures = validateExamples();
if (failures.length) {
  console.error(`✗ ${failures.length} invalid example(s):\n  ${failures.join("\n  ")}`);
  process.exit(1);
}

const yaml =
  "# GENERATED by `pnpm openapi` from src/contract — do not edit by hand.\n" +
  stringify(generateOpenApiDocument(), { lineWidth: 0, aliasDuplicateObjects: false });

const AUTH: Record<Exchange["actor"], string | null> = {
  agent: "Authorization: Bearer <agent token>",
  user: "Cookie: agenda_session=<session>",
  anonymous: null,
  internal: "X-Internal-Token: <INTERNAL_TOKEN>",
};

const json = (v: unknown) => JSON.stringify(v, null, 2);

function fold(label: string, body: string, lang: string) {
  const block = "```" + lang + "\n" + body + "\n```";
  return body.split("\n").length > 40 ? `<details><summary>${label}</summary>\n\n${block}\n\n</details>` : block;
}

function renderExchange(r: RouteDef, e: Exchange) {
  let path = r.path;
  for (const [k, v] of Object.entries(e.params ?? {})) path = path.replace(`{${k}}`, encodeURIComponent(v));
  const qs = e.query ? "?" + new URLSearchParams(e.query).toString() : "";
  const head = [
    `${r.method.toUpperCase()} ${path}${qs}`,
    AUTH[e.actor],
    ...Object.entries(e.headers ?? {}).map(([k, v]) => `${k}: ${v}`),
    ...(e.body !== undefined ? ["Content-Type: application/json"] : []),
  ].filter(Boolean);
  const req = head.join("\n") + (e.body !== undefined ? "\n\n" + json(e.body) : "");
  const resHead = [
    `HTTP/1.1 ${e.status} ${reason(e.status)}`,
    ...(e.response !== undefined
      ? [`Content-Type: ${e.status >= 400 && !effectiveResponses(r)[e.status]?.schema ? "application/problem+json" : "application/json"}`]
      : []),
    ...Object.entries(e.responseHeaders ?? {}).map(([k, v]) => `${k}: ${v}`),
  ];
  const res = resHead.join("\n") + (e.response !== undefined ? "\n\n" + json(e.response) : "");
  return [
    `#### ${e.summary}`,
    `_${e.actor}_${e.invalidRequest ? " · intentionally invalid request" : ""}`,
    "",
    fold("Request", req, "http"),
    "",
    fold(`Response ${e.status}`, res, "http"),
  ].join("\n");
}

const tags = [...new Set(routes.map((r) => r.tag))];
const md = [
  "# API examples",
  "",
  "> GENERATED by `pnpm openapi` from `src/contract` (every example is validated against the schemas). Do not edit by hand.",
  "",
  "Scenario: Monday 2026-10-19. Agenbot loads the day at 07:00 with options A and B; I choose A at 07:42,",
  "mark Martín's call done, move reading; I move Laura's call in Google, Agenbot re-sends the day → proposal → I accept.",
  "",
  "Errors common to every route (400 `validation_error`, 401, 403, 409 `idempotency_in_progress`, 422 `idempotency_key_reuse`, 429 `rate_limited`) are listed in `openapi.yaml`.",
  "",
  "## Contents",
  "",
  ...tags.flatMap((t) => [`- **${t}**: ` + routes.filter((r) => r.tag === t).map((r) => `\`${r.method.toUpperCase()} ${r.path}\``).join(", ")]),
  "- **Webhook**: `POST ${AGENT_WEBHOOK_URL}`",
  "",
  ...tags.flatMap((t) => [
    `## ${t}`,
    "",
    ...routes
      .filter((r) => r.tag === t)
      .flatMap((r) => [
        `### \`${r.method.toUpperCase()} ${r.path}\` — ${r.summary}`,
        "",
        `Access: **${r.access}**${r.description ? "\n\n" + r.description : ""}`,
        "",
        ...r.exchanges.map((e) => renderExchange(r, e) + "\n"),
      ]),
  ]),
  "## Webhook",
  "",
  "### `POST ${AGENT_WEBHOOK_URL}` — my changes, sent to Agenbot",
  "",
  ...webhookExamples.flatMap((w) => [
    `#### ${w.summary}`,
    "",
    fold(
      "Request",
      [
        "POST ${AGENT_WEBHOOK_URL}",
        "Authorization: Bearer ${AGENT_WEBHOOK_TOKEN}",
        `Idempotency-Key: ${w.value.batchId}`,
        "Content-Type: application/json",
        "",
        json(w.value),
      ].join("\n"),
      "http",
    ),
    "",
  ]),
].join("\n");

const targets: Array<[string, string]> = [
  ["openapi.yaml", yaml],
  ["docs/api-examples.md", md],
];

if (check) {
  const stale = targets.filter(([f, content]) => {
    try {
      return readFileSync(f, "utf8").replace(/\r\n/g, "\n") !== content;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`✗ Contract drift: ${stale.map(([f]) => f).join(", ")} out of date. Run \`pnpm openapi\` and commit.`);
    process.exit(1);
  }
  console.log(`✓ ${routes.length} routes, examples valid, generated files up to date`);
} else {
  for (const [f, content] of targets) writeFileSync(f, content);
  console.log(`✓ wrote ${targets.map(([f]) => f).join(", ")} (${routes.length} routes)`);
}
