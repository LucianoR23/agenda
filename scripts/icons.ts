/**
 * Builds public/icons.svg (one <symbol> per icon in src/ui/icons.ts) from @material-symbols/svg-400/rounded.
 *   pnpm icons          write the sprite
 *   pnpm icons:check    fail if the sprite is stale (CI)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { ICONS } from "../src/ui/icons";

const require = createRequire(import.meta.url);
const dir = join(dirname(require.resolve("@material-symbols/svg-400/package.json")), "rounded");
const OUT = "public/icons.svg";

/** Names from the design whose glyph was renamed in the current Material Symbols release. */
const SOURCE: Partial<Record<(typeof ICONS)[number], string>> = {
  auto_awesome: "star_shine",
  insights: "monitoring",
  system_update: "mobile_arrow_down",
};

const symbols = [...ICONS].sort().map((name) => {
  const svg = readFileSync(join(dir, `${SOURCE[name] ?? name}.svg`), "utf8");
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  const body = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  if (!viewBox || !body) throw new Error(`cannot parse icon ${name}`);
  return `<symbol id="${name}" viewBox="${viewBox}">${body}</symbol>`;
});

const sprite =
  `<svg xmlns="http://www.w3.org/2000/svg"><!-- GENERATED by pnpm icons from src/ui/icons.ts · Material Symbols Rounded (Apache-2.0) -->\n` +
  symbols.join("\n") +
  "\n</svg>\n";

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8").replace(/\r\n/g, "\n");
  } catch {}
  if (current !== sprite) {
    console.error(`✗ ${OUT} is stale. Run \`pnpm icons\` and commit.`);
    process.exit(1);
  }
  console.log(`✓ ${OUT} up to date (${ICONS.length} icons)`);
} else {
  writeFileSync(OUT, sprite);
  console.log(`✓ wrote ${OUT} (${ICONS.length} icons, ${Math.round(sprite.length / 1024)} KB)`);
}
