/**
 * The service worker, served from a route so it carries the app version: every deploy is a byte-different script,
 * so browsers see the update, and the cache name (`agenda-<version>`) changes with it (docs/v2/07).
 */
export function GET() {
  const version = (process.env.APP_VERSION ?? "dev").replace(/[^\w.-]/g, "");
  return new Response(serviceWorker(version), {
    headers: {
      "Content-Type": "application/javascript; charset=utf-8",
      "Cache-Control": "no-cache",
      "Service-Worker-Allowed": "/",
    },
  });
}

function serviceWorker(version: string) {
  return `/* Agenda service worker ${version} (generated by src/app/sw.js/route.ts)
 * - App shell: navigations network-first, the cached page when offline.
 * - /_next/static: cache-first (hashed, immutable). Icons and other assets: stale-while-revalidate.
 * - /api is never cached here: data lives in IndexedDB (the app's cache + write outbox).
 * - Push: reminders with Listo / Posponer (signed single-use token, no session needed); notices open the app.
 * - Updates wait until the app says "SKIP_WAITING" (the "Actualizar" toast), then every old cache is deleted.
 */
const VERSION = "agenda-${version}";
const SHELL = VERSION + "-shell";
const STATIC = VERSION + "-static";
const SHELL_URLS = ["/", "/inbox", "/tareas", "/calendario", "/recordatorios", "/habitos", "/historial", "/cierre", "/ajustes", "/icons.svg", "/icons/icon-192.png", "/manifest.webmanifest"];

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(SHELL).then((c) => Promise.all(SHELL_URLS.map((u) => c.add(u).catch(() => undefined)))));
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  // drop every cache that isn't this version's (v1's "agenda-v2…" included)
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => !k.startsWith(VERSION + "-")).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith("/api/") || url.pathname === "/sw.js") return;

  if (req.mode === "navigate") {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(SHELL).then((c) => c.put(url.pathname, copy));
          }
          return res;
        })
        .catch(async () => (await caches.match(url.pathname)) || (await caches.match("/")) || Response.error()),
    );
    return;
  }

  if (url.pathname.startsWith("/_next/static/")) {
    event.respondWith(
      caches.match(req).then(
        (hit) =>
          hit ||
          fetch(req).then((res) => {
            if (res.ok) {
              const copy = res.clone();
              caches.open(STATIC).then((c) => c.put(req, copy));
            }
            return res;
          }),
      ),
    );
    return;
  }

  event.respondWith(
    caches.match(req).then((hit) => {
      const net = fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(STATIC).then((c) => c.put(req, copy));
          }
          return res;
        })
        .catch(() => hit);
      return hit || net;
    }),
  );
});

self.addEventListener("push", (event) => {
  let msg = { type: "notice", title: "Agenda", body: "", url: "/" };
  try {
    msg = { ...msg, ...event.data.json() };
  } catch {}
  const options = {
    body: msg.body,
    tag: msg.tag,
    icon: "/icons/icon-192.png",
    badge: "/icons/badge-96.png",
    data: { url: msg.url, token: msg.actionToken, type: msg.type },
    vibrate: [40, 30, 40],
  };
  if (msg.type === "reminder" && msg.actions && msg.actionToken) {
    options.actions = msg.actions;
    options.requireInteraction = true;
  }
  event.waitUntil(self.registration.showNotification(msg.title, options));
});

async function openApp(url) {
  const wins = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
  for (const w of wins) {
    if ("focus" in w) {
      await w.navigate(url).catch(() => undefined);
      return w.focus();
    }
  }
  return self.clients.openWindow(url);
}

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const data = event.notification.data || {};
  const url = data.url || "/";
  if ((event.action === "done" || event.action === "snooze") && data.token) {
    event.waitUntil(
      fetch("/api/push/action", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ token: data.token, action: event.action }),
      })
        .then((res) => (res.ok || res.status === 409 ? undefined : openApp(url)))
        .catch(() => openApp(url)), // offline: let the app handle it
    );
    return;
  }
  event.waitUntil(openApp(url));
});
`;
}
